<?php

use Site\Embed;

Embed::SetTitle("Osekai • Licences");
Embed::SetDescription("The open source software Osekai is built with");

// ported from anthera: views/licences.php
function renderLicence(array $package)
{
    static $seen = [];

    if (isset($seen[$package['name']])) {
        // already rendered this package, skip it
        return;
    }

    $seen[$package['name']] = true;

    $package['licenseText'] = str_replace("\n\n", "LFLFLLFLF", $package['licenseText']);
    $package['licenseText'] = str_replace("\n", " ", $package['licenseText']);
    $package['licenseText'] = str_replace("LFLFLLFLF", "\n\n", $package['licenseText']);
    echo "<div class='licence'>";
    echo "  <h3><a href='" . htmlspecialchars($package['url'] ?? "") . "' target='_blank' rel='noopener noreferrer'>" . htmlspecialchars($package['name']) . "</a><span>" . htmlspecialchars($package['licenseName'] ?? "") . "</span></h3>";
    echo "  <p>" . nl2br(htmlspecialchars(trim($package['licenseText']))) . "</p>";

    if (!empty($package['dependencies'])) {
        echo "  <div>\n";
        foreach ($package['dependencies'] as $dep) {
            renderLicence($dep);
        }
        echo "  </div>\n";
    }

    echo "</div>\n";
}

// frontend, generated by frontend/scripts/licences.js on deploy
$frontendPackages = [];
if (file_exists("./frontend/licences.json")) {
    $frontendPackages = json_decode(file_get_contents("./frontend/licences.json"), true);
}

// backend, straight from composer
$backendPackages = [];
if (file_exists("./vendor/composer/installed.json")) {
    $installed = json_decode(file_get_contents("./vendor/composer/installed.json"), true);
    $devPackages = $installed['dev-package-names'] ?? [];

    foreach ($installed['packages'] ?? [] as $package) {
        if (in_array($package['name'], $devPackages)) continue;

        $licenseText = "(license text not found)";
        foreach (["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "LICENCE.md", "COPYING"] as $file) {
            $path = "./vendor/" . $package['name'] . "/" . $file;
            if (file_exists($path)) {
                $licenseText = file_get_contents($path);
                break;
            }
        }

        $url = $package['homepage'] ?? null;
        if ($url == null) {
            $url = $package['source']['url'] ?? "https://packagist.org/packages/" . $package['name'];
        }

        $backendPackages[] = [
            "name" => $package['name'],
            "licenseName" => implode(", ", $package['license'] ?? []),
            "licenseText" => $licenseText,
            "url" => $url,
            "dependencies" => []
        ];
    }
}
?>
<div class="page-container-inner">
    <div class="markdown dark">
        <h1>Licences</h1>
        <p>Osekai is built on top of a lot of open source software. Thank you to everyone who works on these!</p>
    </div>

    <div class="licences">
        <?php
        foreach ($frontendPackages as $package) {
            renderLicence($package);
        }
        foreach ($backendPackages as $package) {
            renderLicence($package);
        }
        ?>
    </div>
</div>

<div class="page-padder"></div>

